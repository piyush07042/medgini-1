from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any


@dataclass
class AgentResult:
    """
    Standard response returned by every AI agent.

    This class guarantees that all agents return data in
    exactly the same format.

    Example
    -------
    AgentResult(
        agent="RiskAgent",
        status="SUCCESS",
        confidence=0.94,
        result={"risk": "High"},
        evidence=["ESC Guideline 2023"],
        warnings=[],
        processing_time=0.82
    )
    """

    agent: str

    status: str = "SUCCESS"

    result: Any = None

    confidence: float = 0.0

    evidence: list[str] = field(default_factory=list)

    warnings: list[str] = field(default_factory=list)

    metadata: dict[str, Any] = field(default_factory=dict)

    processing_time: float = 0.0

    timestamp: datetime = field(default_factory=datetime.utcnow)

    error: str | None = None

    # --- Phase 8: AI Workflow Improvements ---
    quality_score: float = 0.0

    guardrail_violations: list[str] = field(default_factory=list)

    evaluation: dict[str, Any] = field(default_factory=dict)

    def add_warning(self, warning: str) -> None:
        """Append a warning generated by the agent."""
        self.warnings.append(warning)

    def add_evidence(self, evidence: str) -> None:
        """Append supporting evidence."""
        self.evidence.append(evidence)

    def set_error(self, message: str) -> None:
        """Mark this result as failed."""
        self.status = "FAILED"
        self.error = message

    @property
    def success(self) -> bool:
        """True if execution completed successfully."""
        return self.status == "SUCCESS"

    def to_dict(self) -> dict[str, Any]:
        """
        Serialize AgentResult into JSON-compatible dictionary.
        """

        return {
            "agent": self.agent,
            "status": self.status,
            "result": self.result,
            "confidence": self.confidence,
            "evidence": self.evidence,
            "warnings": self.warnings,
            "metadata": self.metadata,
            "processing_time": self.processing_time,
            "timestamp": self.timestamp.isoformat(),
            "error": self.error,
            "quality_score": self.quality_score,
            "guardrail_violations": self.guardrail_violations,
            "evaluation": self.evaluation,
        }